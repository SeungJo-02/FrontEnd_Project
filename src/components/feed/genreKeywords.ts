/**
 * 장르명에서 도서 검색어 후보를 뽑는다.
 *
 * 빈 피드 안내는 관심 장르 이름을 그대로 검색어로 써서 책을 찾는다. 그런데
 * '만화/라이트노벨'처럼 슬래시로 묶인 이름을 통째로 넣으면 제목에 거의 걸리지 않는다.
 * 운영에서 확인한 결과 '만화/라이트노벨'은 2건뿐이고 2페이지부터는 빈손이라, 어느
 * 페이지를 뽑아도 늘 같은 2권으로 되돌아왔다("다른 책" 버튼이 반응 없어 보이던 원인).
 *
 * 슬래시로 쪼개면 '만화' 8건, '라이트노벨' 8건으로 늘고 페이지마다 다른 책이 나온다.
 * 후보가 여럿이면 호출부가 매번 하나를 골라 결과에 변화를 준다.
 */
export function keywordsFor(genreName: string): string[] {
  const parts = genreName
    .split('/')
    .map(part => part.trim())
    .filter(Boolean)
  // 슬래시가 없거나 공백뿐이면 원래 이름을 그대로 쓴다.
  return parts.length > 0 ? parts : [genreName]
}
