export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'name' | 'ref'> {
  name: IconName
  /** 선택·활성 상태처럼 꽉 찬 표현. 채움 변형이 없는 아이콘이면 외곽선 그대로 렌더된다. */
  filled?: boolean
}

/**
 * 아이콘 하나를 그린다.
 *
 * 크기는 글자 크기를 따라가므로(`1em`) 호출부에서 `text-2xl`·`text-[18px]`처럼
 * 기존 방식 그대로 지정하면 된다. 색도 `currentColor`라 `text-primary`가 그대로 먹는다.
 *
 * 기본은 장식용이라 `aria-hidden`이다. 의미를 전달해야 하면 `aria-hidden={false}`와
 * `aria-label`을 함께 넘긴다.
 */
export default function Icon({ name, filled = false, className, ...rest }: IconProps) {
  const def: IconDef = ICONS[name]
  const useFilled = filled && Boolean(def.filled)
  const body = useFilled ? def.filled : def.outline
  // filled가 굵은 선으로 표현되는 아이콘(search 등)은 채우면 안 된다.
  const paint =
    useFilled && !def.filledIsStroke
      ? { fill: 'currentColor', stroke: 'none' }
      : { fill: 'none', stroke: 'currentColor' }

  return (
    <svg
      viewBox="0 0 24 24"
      width="1em"
      height="1em"
      strokeWidth={1.6}
      strokeLinecap="round"
      strokeLinejoin="round"
      // 아이콘 폰트가 글줄에 앉던 위치를 그대로 재현해 기존 레이아웃이 흔들리지 않게 한다.
      className={cn('inline-block shrink-0 align-[-0.125em]', className)}
      aria-hidden="true"
      focusable="false"
      {...paint}
      {...rest}
    >
      {body}
    </svg>
  )
}
